/**
 * Get random questions for a complete 5-level game run.
 * Exactly 3 questions per level = 15 questions total.
 * In a 180-second (3-minute) limit, this gives ~12 seconds per question,
 * perfectly meeting the "게임이 3분 이내에 끝나도록 짧고 반복적으로" constraint!
 */
export function getGameQuestions(): Question[] {
  const result: Question[] = [];
  for (let lvl = 1; lvl <= 5; lvl++) {
    const levelQuestions = ALL_QUESTIONS.filter((q) => q.level === lvl);
    // Shuffle level questions and pick 3
    const shuffled = [...levelQuestions].sort(() => Math.random() - 0.5);
    result.push(...shuffled.slice(0, 3));
  }
  return result;
}
